CREATE TRIGGER insert_animal_status
AFTER INSERT ON applications
FOR EACH ROW
BEGIN
    -- Check if the new status is 'Accepted'
    IF NEW.status = 'accepted' THEN
        UPDATE pets
        SET status = 'adopted'
        WHERE petID = NEW.petID;
    END IF;
END $$

