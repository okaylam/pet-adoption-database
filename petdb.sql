DROP TABLE IF EXISTS medical_records;
DROP TABLE IF EXISTS adoptions;
DROP TABLE IF EXISTS applications;
DROP TABLE IF EXISTS pets;
DROP TABLE IF EXISTS applicants;

CREATE TABLE applicants (
    applicantID INT NOT NULL,
    firstName VARCHAR(50) DEFAULT NULL,
    lastName VARCHAR(50) DEFAULT NULL,
    email VARCHAR(50) DEFAULT NULL,
    phone VARCHAR(30) DEFAULT NULL,
    address VARCHAR(100) DEFAULT NULL,
    PRIMARY KEY (applicantID)
);

CREATE TABLE pets (
    petID INT NOT NULL,
    name VARCHAR(50) DEFAULT NULL,
    petType VARCHAR(50) DEFAULT NULL,
    breed VARCHAR(50) DEFAULT NULL,
    ageMonths INT DEFAULT NULL,
    color VARCHAR(50) DEFAULT NULL,
    weightKG DECIMAL(10,2) DEFAULT NULL,
    status VARCHAR(30) DEFAULT NULL,
    PRIMARY KEY (petID)
);

CREATE TABLE applications (
    applicationID INT NOT NULL,
    applicantID INT NOT NULL,
    petID INT NOT NULL,
    submissionDate DATE DEFAULT NULL,
    status VARCHAR(30) DEFAULT 'Pending',
    PRIMARY KEY (applicationID),
    FOREIGN KEY (applicantID) REFERENCES applicants(applicantID),
    FOREIGN KEY (petID) REFERENCES pets(petID)
);

CREATE TABLE adoptions (
    adoptionID INT NOT NULL,
    petID INT NOT NULL,
    applicantID INT NOT NULL,
    applicationID INT NOT NULL,
    adoptionDate DATE DEFAULT NULL,
    PRIMARY KEY (adoptionID),
    FOREIGN KEY (applicantID) REFERENCES applicants(applicantID),
    FOREIGN KEY (applicationID) REFERENCES applications(applicationID),
    FOREIGN KEY (petID) REFERENCES pets(petID)
);

CREATE TABLE medical_records (
    recordID INT NOT NULL,
    petID INT NOT NULL,
    visitDate DATE NOT NULL,
    recordType VARCHAR(50) NOT NULL,
    diagnosis VARCHAR(255) DEFAULT NULL,
    treatment VARCHAR(255) DEFAULT NULL,
    vaccineType VARCHAR(100) DEFAULT NULL,
    PRIMARY KEY (recordID),
    FOREIGN KEY (petID) REFERENCES pets(petID)
);

