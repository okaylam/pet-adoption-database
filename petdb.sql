DROP PROCEDURE IF EXISTS verify_adoptions;
DELIMITER $$
CREATE PROCEDURE verify_adoptions()
BEGIN
  -- Update pets status to 'Adopted' for all pets with an accepted application
  UPDATE pets AS p
    JOIN applications AS a
      ON p.petID = a.petID
  SET p.status = 'Adopted'
  WHERE a.status = 'Accepted'; -- Use 'Accepted' string

  -- Update applications status to 'Completed'
  UPDATE applications
  SET status = 'Completed'
  WHERE status = 'Accepted'; -- Use 'Accepted' string
END;
$$
